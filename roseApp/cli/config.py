@app.command()
def init(
    force: bool = typer.Option(False, "--force", "-f", help="Overwrite existing configuration file"),
    template: str = typer.Option("default", "--template", "-t", help="Configuration template to use")
):
    """Initialize a default configuration file."""
    
    config_file = Path("rose.config.yaml")
    
    if config_file.exists() and not force:
        console.print(f"[{get_color('warning')}]Configuration file already exists: {config_file}[/{get_color('warning')}]")
        console.print(f"Use [{get_color('accent')}]--force[/{get_color('accent')}] to overwrite")
        raise typer.Exit(1)
    
    try:
        # Create default configuration
        default_config = {
            "# Rose Configuration File": None,
            "# Performance Settings": None,
            "parallel_workers": 4,
            "memory_limit_mb": 512,
            
            "# Feature Toggles": None,
            "enable_cache": True,
            "enable_plugins": True,
            
            "# Default Behavior": None,
            "compression_default": "none",
            "verbose_default": False,
            "build_index_default": False,
            
            "# Logging Settings": None,
            "log_level": "INFO",
            "log_to_file": True,
            
            "# UI Settings": None,
            "theme_file": "rose.theme.default.yaml",
            "enable_colors": True,
            
            "# Directory Settings": None,
            "output_directory": "output",
        }
        
        # Remove comment keys for YAML output
        yaml_config = {k: v for k, v in default_config.items() if not k.startswith("#")}
        
        # Write configuration file with comments
        with open(config_file, 'w') as f:
            f.write("# Rose Configuration File\n")
            f.write("# Generated by: rose config init\n\n")
            
            f.write("# Performance Settings\n")
            f.write(f"parallel_workers: {yaml_config['parallel_workers']}\n")
            f.write(f"memory_limit_mb: {yaml_config['memory_limit_mb']}\n\n")
            
            f.write("# Feature Toggles\n")
            f.write(f"enable_cache: {str(yaml_config['enable_cache']).lower()}\n")
            f.write(f"enable_plugins: {str(yaml_config['enable_plugins']).lower()}\n\n")
            
            f.write("# Default Behavior\n")
            f.write(f"compression_default: {yaml_config['compression_default']}\n")
            f.write(f"verbose_default: {str(yaml_config['verbose_default']).lower()}\n")
            f.write(f"build_index_default: {str(yaml_config['build_index_default']).lower()}\n\n")
            
            f.write("# Logging Settings\n")
            f.write(f"log_level: {yaml_config['log_level']}\n")
            f.write(f"log_to_file: {str(yaml_config['log_to_file']).lower()}\n\n")
            
            f.write("# UI Settings\n")
            f.write(f"theme_file: {yaml_config['theme_file']}\n")
            f.write(f"enable_colors: {str(yaml_config['enable_colors']).lower()}\n\n")
            
            f.write("# Directory Settings\n")
            f.write(f"output_directory: {yaml_config['output_directory']}\n")
        
        console.print(f"[{get_color('success')}]✓[/{get_color('success')}] Configuration file created: [{get_color('path')}]{config_file}[/{get_color('path')}]")
        console.print(f"[{get_color('muted')}]Edit the file to customize your settings[/{get_color('muted')}]")
        
    except Exception as e:
        console.print(f"[{get_color('error')}]Error creating configuration file: {e}[/{get_color('error')}]")
        raise typer.Exit(1)

@app.command()
def show(
    key: Optional[str] = typer.Argument(None, help="Specific configuration key to show"),
    format: str = typer.Option("table", "--format", "-f", help="Output format: table, yaml, json")
):
    """Show current configuration."""
    
    try:
        config = get_config()
        
        if key:
            # Show specific key
            if hasattr(config, key):
                value = getattr(config, key)
                console.print(f"[{get_color('accent')}]{key}[/{get_color('accent')}]: [{get_color('highlight')}]{value}[/{get_color('highlight')}]")
            else:
                console.print(f"[{get_color('error')}]Configuration key not found: {key}[/{get_color('error')}]")
                raise typer.Exit(1)
        else:
            # Show all configuration
            if format == "table":
                _show_config_table(config)
            elif format == "yaml":
                _show_config_yaml(config)
            elif format == "json":
                _show_config_json(config)
            else:
                console.print(f"[{get_color('error')}]Invalid format: {format}[/{get_color('error')}]")
                raise typer.Exit(1)
                
    except Exception as e:
        console.print(f"[{get_color('error')}]Error reading configuration: {e}[/{get_color('error')}]")
        raise typer.Exit(1)

@app.command()
def set(
    key: str = typer.Argument(..., help="Configuration key to set"),
    value: str = typer.Argument(..., help="Value to set"),
    config_file: Optional[str] = typer.Option(None, "--config", "-c", help="Configuration file path")
):
    """Set a configuration value."""
    
    config_path = Path(config_file) if config_file else Path("rose.config.yaml")
    
    if not config_path.exists():
        console.print(f"[{get_color('error')}]Configuration file not found: {config_path}[/{get_color('error')}]")
        console.print(f"[{get_color('muted')}]Run [{get_color('accent')}]rose config init[/{get_color('accent')}] to create one[/{get_color('muted')}]")
        raise typer.Exit(1)
    
    try:
        # Load existing configuration
        with open(config_path, 'r') as f:
            config_data = yaml.safe_load(f) or {}
        
        # Validate key exists in RoseConfig
        config = get_config()
        if not hasattr(config, key):
            console.print(f"[{get_color('error')}]Invalid configuration key: {key}[/{get_color('error')}]")
            _show_available_keys()
            raise typer.Exit(1)
        
        # Convert value to appropriate type
        converted_value = _convert_value(key, value, config)
        
        # Update configuration
        config_data[key] = converted_value
        
        # Write back to file
        with open(config_path, 'w') as f:
            yaml.dump(config_data, f, default_flow_style=False, sort_keys=False)
        
        console.print(f"[{get_color('success')}]✓[/{get_color('success')}] Set [{get_color('accent')}]{key}[/{get_color('accent')}] = [{get_color('highlight')}]{converted_value}[/{get_color('highlight')}]")
        console.print(f"[{get_color('muted')}]Configuration saved to: {config_path}[/{get_color('muted')}]")
        
    except Exception as e:
        console.print(f"[{get_color('error')}]Error setting configuration: {e}[/{get_color('error')}]")
        raise typer.Exit(1)

