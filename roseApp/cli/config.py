def _convert_value(key: str, value: str, config: RoseConfig):
    """Convert string value to appropriate type based on configuration field."""
    
    field_type = type(getattr(config, key))
    
    if field_type == bool:
        return value.lower() in ('true', '1', 'yes', 'on')
    elif field_type == int:
        return int(value)
    elif field_type == float:
        return float(value)
    elif key == "compression_default":
        if value not in [e.value for e in CompressionType]:
            raise ValueError(f"Invalid compression type: {value}. Valid options: {[e.value for e in CompressionType]}")
        return value
    elif key == "log_level":
        if value not in [e.value for e in LogLevel]:
            raise ValueError(f"Invalid log level: {value}. Valid options: {[e.value for e in LogLevel]}")
        return value
    else:
        return value

