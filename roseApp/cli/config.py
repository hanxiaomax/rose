@app.command()
def validate(
    config_file: Optional[str] = typer.Option(None, "--config", "-c", help="Configuration file path")
):
    """Validate configuration file."""
    
    config_path = Path(config_file) if config_file else Path("rose.config.yaml")
    
    if not config_path.exists():
        console.print(f"[{get_color('error')}]Configuration file not found: {config_path}[/{get_color('error')}]")
        raise typer.Exit(1)
    
    try:
        # Try to load and validate configuration
        config = get_config()
        
        console.print(f"[{get_color('success')}]✓[/{get_color('success')}] Configuration is valid")
        console.print(f"[{get_color('muted')}]Loaded from: {config._loaded_config_path or 'defaults'}[/{get_color('muted')}]")
        
        # Show any warnings
        if hasattr(config, '_validation_warnings') and config._validation_warnings:
            console.print(f"\n[{get_color('warning')}]Warnings:[/{get_color('warning')}]")
            for warning in config._validation_warnings:
                console.print(f"  [{get_color('warning')}]•[/{get_color('warning')}] {warning}")
        
    except Exception as e:
        console.print(f"[{get_color('error')}]Configuration validation failed: {e}[/{get_color('error')}]")
        raise typer.Exit(1)

def _show_config_table(config: RoseConfig):
    """Show configuration in table format."""
    
    table = Table(title="Rose Configuration")
    table.add_column("Setting", style=get_color('accent'), width=25)
    table.add_column("Value", style=get_color('highlight'), width=20)
    table.add_column("Description", style=get_color('muted'), width=40)
    
    # Performance Settings
    table.add_row("parallel_workers", str(config.parallel_workers), "Number of parallel workers")
    table.add_row("memory_limit_mb", str(config.memory_limit_mb), "Memory limit in MB")
    
    # Feature Toggles
    table.add_row("enable_cache", str(config.enable_cache), "Enable caching system")
    table.add_row("enable_plugins", str(config.enable_plugins), "Enable plugin system")
    
    # Default Behavior
    table.add_row("compression_default", config.compression_default, "Default compression type")
    table.add_row("verbose_default", str(config.verbose_default), "Default verbose mode")
    table.add_row("build_index_default", str(config.build_index_default), "Default build index")
    
    # Logging Settings
    table.add_row("log_level", config.log_level, "Logging level")
    table.add_row("log_to_file", str(config.log_to_file), "Enable file logging")
    
    # UI Settings
    table.add_row("theme_file", config.theme_file, "Theme file name")
    table.add_row("enable_colors", str(config.enable_colors), "Enable colored output")
    
    # Directory Settings
    table.add_row("output_directory", config.output_directory, "Default output directory")
    
    console.print(table)
    
    # Show file source
    if hasattr(config, '_loaded_config_path') and config._loaded_config_path:
        console.print(f"\n[{get_color('muted')}]Loaded from: {config._loaded_config_path}[/{get_color('muted')}]")

